// @vitest-environment node
// scripts/check-i18n.mjs, rule 6 (docs/m2/03-desktop-app.md §18.1; README WA63): every desktop bridge error code of
// platform/desktop/codes.gen.ts but the update.* ones has a desktop.errors.<code> message, and rule 4 counts those
// messages as used. platform/desktop/codes.node.test.ts checks the same mapping in test:web.
import { execFile } from 'node:child_process';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';

import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import { BRIDGE_ERRORS, checkBridgeCodes, checkI18n } from '../../scripts/check-i18n.mjs';

const SCRIPT = fileURLToPath(new URL('../../scripts/check-i18n.mjs', import.meta.url));
const WEB_SRC = fileURLToPath(new URL('..', import.meta.url));
const EN_JSON = path.join(WEB_SRC, 'i18n', 'en.json');
const run = promisify(execFile);

const CODES_GEN = `// Code generated by tygo. DO NOT EDIT.
export const CodeInvalidArgument = "invalid_argument";
export const CodeEngineInternal = "engine.internal";
export const CodeUpdateNetwork = "update.network";
export type Code = typeof CodeInvalidArgument | typeof CodeEngineInternal | typeof CodeUpdateNetwork;
/**
 * UpdatePrefix starts every update code.
 */
export const UpdatePrefix = "update.";
`;

type Catalog = Parameters<typeof checkBridgeCodes>[0]['catalog'];
const asCatalog = (c: unknown): Catalog => c as Catalog;

function desktopCatalog(): { desktop: { errors: Record<string, unknown> } } {
  return {
    desktop: {
      errors: {
        invalid_argument: 'Something in that request was wrong.',
        engine: { internal: 'The sharing engine failed.' },
      },
    },
  };
}

describe('check-i18n.mjs bridge-code rule on fixture trees', () => {
  let dir = '';
  let srcDir = '';
  let catalogPath = '';
  const write = async (rel: string, content: unknown): Promise<void> => {
    const file = path.join(srcDir, rel);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, typeof content === 'string' ? content : JSON.stringify(content));
  };

  beforeEach(async () => {
    dir = await mkdtemp(path.join(tmpdir(), 'isshoni-check-i18n-codes-'));
    srcDir = path.join(dir, 'src');
    catalogPath = path.join(srcDir, 'i18n', 'en.json');
    // An entry module (rule 5 follows the imports from it) that loads no lazy namespace.
    await write('main.tsx', 'export {};\n');
    await write('i18n/en.json', {});
    await write('i18n/lazy/desktop.ts', "import { addMessages } from '../index';\naddMessages({});\n");
    await write('i18n/lazy/desktop.en.json', desktopCatalog());
    await write(BRIDGE_ERRORS.file, CODES_GEN);
  });

  afterEach(async () => {
    await rm(dir, { recursive: true, force: true });
  });

  it('passes when every code but the update ones has its message, and counts those messages as used', async () => {
    const res = await checkI18n({ srcDir, catalogPath });
    expect(res.problems).toEqual([]);
    expect(res.bridgeCodes).toBe(2);
    expect(res.warnings).toEqual([]);
    const { stdout } = await run(process.execPath, [SCRIPT, '--src', srcDir, '--catalog', catalogPath]);
    expect(stdout).toMatch(/^check:i18n: 2 bridge error codes, each with its desktop\.errors\.<code> text$/m);
  });

  it('fails when a code has no desktop.errors.<code>, pointing at the constant and the lazy file', async () => {
    const c = desktopCatalog();
    c.desktop.errors['engine'] = {};
    await write('i18n/lazy/desktop.en.json', c);
    const failed = run(process.execPath, [SCRIPT, '--src', srcDir, '--catalog', catalogPath]);
    await expect(failed).rejects.toMatchObject({ code: 1 });
    const err = (await failed.catch((e: unknown) => e)) as { stderr: string };
    expect(err.stderr).toMatch(
      /codes\.gen\.ts:3:14: bridge error code "engine\.internal" \(CodeEngineInternal\) has no desktop\.errors\.engine\.internal in \S*desktop\.en\.json/,
    );
    expect(err.stderr).toMatch(/check:i18n: 1 problem\(s\)/);
  });

  it('says so when the message is an object, not a string', async () => {
    const c = desktopCatalog();
    c.desktop.errors['invalid_argument'] = { field: 'Wrong field.' };
    const { problems } = await checkBridgeCodes({ srcDir, catalog: asCatalog(c), catalogName: 'desktop.en.json' });
    expect(problems.map((p) => p.message)).toEqual([
      'bridge error code "invalid_argument" (CodeInvalidArgument): desktop.errors.invalid_argument has sub-keys, not a message in desktop.en.json',
    ]);
  });

  it('exempts only the update codes: without UpdatePrefix they need a message too', async () => {
    await write(BRIDGE_ERRORS.file, CODES_GEN.replace(/^export const UpdatePrefix.*$/m, ''));
    const res = await checkBridgeCodes({
      srcDir,
      catalog: asCatalog(desktopCatalog()),
      catalogName: 'desktop.en.json',
    });
    expect(res.codes).toBe(3);
    expect(res.problems.map((p) => p.message)).toEqual([
      'bridge error code "update.network" (CodeUpdateNetwork) has no desktop.errors.update.network in desktop.en.json',
    ]);
  });

  it('fails when the file has no Code union', async () => {
    await write(BRIDGE_ERRORS.file, 'export const CodeX = "x";\n');
    const res = await checkI18n({ srcDir, catalogPath });
    expect(res.problems.map((p) => p.message)).toEqual(['no `export type Code` union found']);
  });

  it('skips the rule, with a note, for a src tree without codes.gen.ts', async () => {
    await rm(path.join(srcDir, 'platform'), { recursive: true });
    const res = await checkI18n({ srcDir, catalogPath });
    expect(res).toMatchObject({ problems: [], bridgeCodes: null });
    const { stdout } = await run(process.execPath, [SCRIPT, '--src', srcDir, '--catalog', catalogPath]);
    expect(stdout).toMatch(/bridge-code rule skipped/);
  });
});

describe('check-i18n.mjs bridge-code rule on this package', () => {
  it('passes: desktop.en.json has a text for every bridge error code but the update ones', async () => {
    const res = await checkI18n({ srcDir: WEB_SRC, catalogPath: EN_JSON });
    expect(res.problems).toEqual([]);
    expect(res.bridgeCodes).toBeGreaterThan(30);
    // None of those texts is reported as unused any more.
    expect(res.warnings.filter((w) => /"desktop\.errors\.(?!engine\.reason\.)/.test(w.message))).toEqual([]);
  });

  it('fails when a desktop.errors.<code> text is removed from a copy of the src tree', async () => {
    const dir = await mkdtemp(path.join(tmpdir(), 'isshoni-check-i18n-codes-pkg-'));
    try {
      const src = path.join(dir, 'src');
      const desktop = JSON.parse(await readFile(path.join(WEB_SRC, 'i18n', 'lazy', 'desktop.en.json'), 'utf8')) as {
        desktop: { errors: Record<string, unknown> };
      };
      delete desktop.desktop.errors['not_linked'];
      await mkdir(path.join(src, 'i18n', 'lazy'), { recursive: true });
      await mkdir(path.dirname(path.join(src, BRIDGE_ERRORS.file)), { recursive: true });
      await writeFile(path.join(src, 'main.tsx'), 'export {};\n');
      await writeFile(path.join(src, 'i18n', 'en.json'), '{}');
      await writeFile(path.join(src, 'i18n', 'lazy', 'desktop.en.json'), JSON.stringify(desktop));
      await writeFile(path.join(src, 'i18n', 'lazy', 'desktop.ts'), "import '../index';\n");
      await writeFile(
        path.join(src, BRIDGE_ERRORS.file),
        await readFile(path.join(WEB_SRC, BRIDGE_ERRORS.file), 'utf8'),
      );
      const res = await checkI18n({ srcDir: src, catalogPath: path.join(src, 'i18n', 'en.json') });
      expect(res.problems.map((p) => p.message)).toEqual([
        expect.stringMatching(
          /^bridge error code "not_linked" \(CodeNotLinked\) has no desktop\.errors\.not_linked in /,
        ),
      ]);
    } finally {
      await rm(dir, { recursive: true, force: true });
    }
  });
});
